#!/bin/bash
# ──────────────────────────────────────────────
# ePHEM: in proxy mode, Odoo's ports answer the proxy machine only
#
# With SERVER_ACCESS=proxy, Odoo is published on PROXY_BIND_HOST, ports 8069
# (web) and 8072 (live updates), for an nginx on another machine, and Odoo
# trusts the X-Forwarded-* headers that nginx sends (proxy_mode). Anyone
# else who reached those ports could claim any address and step around what
# the proxy enforces: the RPC block, the login throttle, the closed database
# manager. This lets only the PROXY_FROM addresses (.env) in.
#
# ufw and firewalld never see these connections: Docker's NAT rules hand them
# to the container first. Docker's documented place for such a rule is its
# DOCKER-USER chain, which Docker creates and leaves alone. The rules go into
# a root-owned script (/usr/local/sbin/ephem-proxy-ports) that a systemd unit
# runs after Docker starts, so they come back after a reboot and after a
# Docker restart. The addresses are written into that script: nothing is read
# from this checkout, which its owner can edit, when root runs it at boot.
#
# Connections made on this server itself (an SSH tunnel to the bind address,
# the health checks) do not pass DOCKER-USER and keep working.
#
# The proxy's address is often not known when the server is prepared (it may
# be another team's machine, set up after a penetration test). PROXY_FROM can
# then stay empty and be set in .env later, followed by `apply`. Until then
# Odoo's ports answer every machine that reaches PROXY_BIND_HOST, and the
# security check says so. `detect` finds the address once the proxy is in
# use: it holds the live update connections to 8072 open while anyone is
# logged in.
#
# Usage:
#   bash scripts/proxy-firewall.sh detect   which machines are connected to Odoo now
#   bash scripts/proxy-firewall.sh apply    write the rules and put them in force (sudo)
#   bash scripts/proxy-firewall.sh remove   take them out and delete them (sudo)
#   bash scripts/proxy-firewall.sh status   what is in force (sudo for the rule listing)
#   bash scripts/proxy-firewall.sh check    one line for the security check, no sudo;
#                                           exit 0 only when in force and matching .env
# ──────────────────────────────────────────────
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
EPHEM_ROOT="$SCRIPT_DIR"
# shellcheck source=stack-lib.sh
source "$SCRIPT_DIR/scripts/stack-lib.sh"
# shellcheck source=nginx-lib.sh
source "$SCRIPT_DIR/scripts/nginx-lib.sh"     # valid_ipv4, valid_rpc_addr

UNIT=ephem-proxy-ports
UNIT_FILE=/etc/systemd/system/$UNIT.service
RULES=/usr/local/sbin/$UNIT
CTN=ephem-app       # the Odoo container (container_name in docker-compose.yml)

SUDO=""
if [ "$(id -u)" -ne 0 ]; then
    command -v sudo >/dev/null 2>&1 && SUDO=sudo
fi

# PROXY_FROM: IPv4 addresses or ranges, space or comma separated. IPv4 only:
# Odoo is published on an IPv4 address, so that is how the proxy arrives.
proxy_from_list() {
    local a out=()
    for a in $(env_get PROXY_FROM | tr ',' ' '); do
        if valid_rpc_addr "$a" && [[ "$a" != *:* ]]; then
            out+=("$a")
        else
            echo -e "${RED}✗${NC} PROXY_FROM: '$a' is not an IPv4 address or range" >&2
            return 1
        fi
    done
    printf '%s' "${out[*]:-}"
}

need_root_tools() {
    if [ "$(uname -s)" != Linux ] || ! command -v systemctl >/dev/null 2>&1; then
        echo -e "${RED}✗${NC} This needs a Linux server with systemd."
        exit 1
    fi
    if [ "$(id -u)" -ne 0 ] && [ -z "$SUDO" ]; then
        echo -e "${RED}✗${NC} Run as root, or install sudo."
        exit 1
    fi
}

# The script root runs. Values are single-quoted: they were validated as
# addresses, so they hold no quote.
write_rules_script() {  # write_rules_script BIND FROM OUT
    cat > "$3" <<EOF
#!/bin/sh
# Generated by ephem-deploy (scripts/proxy-firewall.sh apply), $(date '+%Y-%m-%d %H:%M').
# Odoo, published on $1 ports 8069 and 8072, answers $2 only.
# Change PROXY_BIND_HOST or PROXY_FROM in that checkout's .env and run apply
# again: an edit here is overwritten.
set -e
BIND='$1'
FROM='$2'
CHAIN=EPHEM-PROXY

# Every DOCKER-USER rule that sends to our chain, whichever address it names
# (an earlier BIND included). iptables -S prints rules in the form iptables
# takes them back.
unhook() {
    iptables -S DOCKER-USER 2>/dev/null | grep -- "-j \$CHAIN\\\$" | sed 's/^-A /-D /' | while read -r rule; do
        iptables \$rule
    done
}

case "\${1:-start}" in
    start)
        if ! iptables -n -L DOCKER-USER >/dev/null 2>&1; then
            echo "$UNIT: no DOCKER-USER chain (is Docker running, with its iptables firewall?)" >&2
            exit 1
        fi
        iptables -N "\$CHAIN" 2>/dev/null || iptables -F "\$CHAIN"
        for src in \$FROM; do
            iptables -A "\$CHAIN" -s "\$src" -j RETURN
        done
        iptables -A "\$CHAIN" -j DROP
        unhook
        for port in 8069 8072; do
            iptables -I DOCKER-USER -p tcp -m conntrack --ctorigdst "\$BIND" --ctorigdstport "\$port" --ctdir ORIGINAL -j "\$CHAIN"
        done
        ;;
    stop)
        unhook
        iptables -F "\$CHAIN" 2>/dev/null || true
        iptables -X "\$CHAIN" 2>/dev/null || true
        ;;
    *)
        echo "usage: \$0 start|stop" >&2
        exit 2
        ;;
esac
EOF
}

write_unit() {  # write_unit OUT
    cat > "$1" <<EOF
[Unit]
Description=ePHEM: Odoo ports open to the proxy machine only (ephem-deploy proxy mode)
After=docker.service
Requires=docker.service
# A Docker restart restarts this too, so the rules are put back after it.
PartOf=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$RULES start
ExecStop=$RULES stop

[Install]
WantedBy=multi-user.target
EOF
}

cmd_apply() {
    need_root_tools
    local bind from tmp
    bind="$(env_get PROXY_BIND_HOST)"
    if ! valid_ipv4 "$bind" || [ "$bind" = 0.0.0.0 ]; then
        echo -e "${RED}✗${NC} PROXY_BIND_HOST in .env is '${bind}': the IPv4 address Odoo is published on is needed (bash setup.sh asks for it)."
        exit 1
    fi
    from="$(proxy_from_list)" || exit 1
    if [ -z "$from" ]; then
        # An empty list would shut the proxy out as well: the site goes down.
        echo -e "${RED}✗${NC} PROXY_FROM in .env is empty: set the proxy machine's address there first."
        echo "     Not known? Once the proxy is in use: bash scripts/proxy-firewall.sh detect"
        exit 1
    fi
    if ! systemctl cat docker.service >/dev/null 2>&1; then
        echo -e "${RED}✗${NC} No docker.service unit here (a snap Docker?). The rules need Docker's own service."
        exit 1
    fi
    if ! $SUDO iptables -n -L DOCKER-USER >/dev/null 2>&1; then
        echo -e "${RED}✗${NC} iptables has no DOCKER-USER chain: Docker is not running, or runs without its iptables firewall."
        exit 1
    fi

    tmp="$(mktemp -d)"
    write_rules_script "$bind" "$from" "$tmp/rules"
    write_unit "$tmp/unit"
    $SUDO install -m 0755 -o root -g root "$tmp/rules" "$RULES"
    $SUDO install -m 0644 -o root -g root "$tmp/unit" "$UNIT_FILE"
    rm -rf "$tmp"
    $SUDO systemctl daemon-reload
    $SUDO systemctl enable "$UNIT" >/dev/null 2>&1
    if ! $SUDO systemctl restart "$UNIT"; then
        echo -e "${RED}✗${NC} The rules did not load: sudo journalctl -u $UNIT"
        exit 1
    fi
    echo -e "${GREEN}✓${NC} Odoo on $bind (ports 8069, 8072) answers $from only"
    echo "     (systemd unit $UNIT, back after every reboot and Docker restart)"
}

cmd_remove() {
    need_root_tools
    if [ -f "$UNIT_FILE" ]; then
        $SUDO systemctl disable --now "$UNIT" >/dev/null 2>&1 || true
        $SUDO rm -f "$UNIT_FILE"
        $SUDO systemctl daemon-reload
    fi
    # The rules script also takes them out when the unit is already gone.
    [ -x "$RULES" ] && $SUDO "$RULES" stop || true
    $SUDO rm -f "$RULES"
    echo -e "${GREEN}✓${NC} Proxy firewall removed: Odoo's published ports answer every address that reaches them"
}

# What the rules script enforces, read from it (it is world readable): the
# BIND= and FROM= lines it was written with.
rules_value() { sed -n "s/^$1='\(.*\)'\$/\1/p" "$RULES" 2>/dev/null | head -1; }

cmd_check() {
    local bind from have_bind have_from
    bind="$(env_get PROXY_BIND_HOST)"; from="$(proxy_from_list 2>/dev/null || true)"
    if [ -z "$from" ]; then
        echo -e "  ${YELLOW}!${NC} proxy machine not set (PROXY_FROM in .env): Odoo's ports on ${bind:-PROXY_BIND_HOST} answer every machine that reaches them."
        echo "     Find it: bash scripts/proxy-firewall.sh detect; set PROXY_FROM, then: bash scripts/proxy-firewall.sh apply"
        return 1
    fi
    if ! systemctl is-active --quiet "$UNIT" 2>/dev/null; then
        echo -e "  ${YELLOW}!${NC} Odoo's ports are open to every address that reaches $bind (no proxy firewall): bash scripts/proxy-firewall.sh apply"
        return 1
    fi
    have_bind="$(rules_value BIND)"; have_from="$(rules_value FROM)"
    if [ "$have_bind" != "$bind" ] || [ "$have_from" != "$from" ]; then
        echo -e "  ${YELLOW}!${NC} the proxy firewall enforces $have_bind for '$have_from', .env says $bind for '$from': bash scripts/proxy-firewall.sh apply"
        return 1
    fi
    echo -e "  ${GREEN}✓${NC} Odoo's ports on $bind answer $from only (proxy firewall)"
}

cmd_status() {
    cmd_check || true
    echo ""
    echo "  Unit $UNIT: $(systemctl is-enabled "$UNIT" 2>/dev/null || echo absent), $(systemctl is-active "$UNIT" 2>/dev/null || true)"
    if [ -n "$SUDO" ] || [ "$(id -u)" -eq 0 ]; then
        echo "  Rules in force:"
        { $SUDO iptables -S DOCKER-USER 2>/dev/null | grep -- '-j EPHEM-PROXY' || true
          $SUDO iptables -S EPHEM-PROXY 2>/dev/null || true; } | sed 's/^/    /'
    fi
}

# The machines connected to Odoo's ports right now, from the Odoo
# container's own socket table (/proc/net/tcp: addresses in hex, the IP
# byte reversed, then the port). Docker keeps the caller's address when it
# forwards a published port, so the far end of a connection to 8069 or 8072
# is the machine that opened it, whatever proxy_mode makes of the headers.
cmd_detect() {
    local gw found
    if ! docker inspect "$CTN" >/dev/null 2>&1; then
        echo -e "${RED}✗${NC} The Odoo container ($CTN) is not running."
        exit 1
    fi
    gw=" $(docker inspect -f '{{range .NetworkSettings.Networks}}{{.Gateway}} {{end}}' "$CTN" 2>/dev/null || true) "
    # 1F85 = 8069, 1F88 = 8072; state 01 = established; 127.x is the
    # container talking to itself (its health check).
    found="$(docker exec "$CTN" cat /proc/net/tcp 2>/dev/null \
        | awk 'NR > 1 && $4 == "01" { print $2, $3 }' \
        | while read -r loc rem; do
              case "${loc##*:}" in 1F85|1F88) ;; *) continue ;; esac
              h="${rem%%:*}"
              ip="$(printf '%d.%d.%d.%d' "0x${h:6:2}" "0x${h:4:2}" "0x${h:2:2}" "0x${h:0:2}")"
              case "$ip" in 127.*) continue ;; esac
              echo "$ip"
          done | sort | uniq -c | sort -rn || true)"
    if [ -z "$found" ]; then
        echo "  No machine is connected to Odoo right now. Open the site through the"
        echo "  proxy in a browser and log in, then run this again."
        return 0
    fi
    echo "  Connected to Odoo (ports 8069 and 8072) right now:"
    while read -r n ip; do
        if [[ "$gw" == *" $ip "* ]]; then
            printf '    %4s  %-16s (this server, through Docker: an SSH tunnel or a local call)\n' "$n" "$ip"
        else
            printf '    %4s  %s\n' "$n" "$ip"
        fi
    done <<< "$found"
    echo ""
    echo "  The proxy holds the live update connections open while anyone is logged"
    echo "  in, so it is the address with most of them. Put it in .env as"
    echo "  PROXY_FROM=<address>, then run: bash scripts/proxy-firewall.sh apply"
}

case "${1:-}" in
    detect) cmd_detect ;;
    apply)  cmd_apply ;;
    remove) cmd_remove ;;
    check)  cmd_check ;;
    status) cmd_status ;;
    *)      sed -n '2,38p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
